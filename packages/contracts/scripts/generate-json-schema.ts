// Writes schema/api-v1.json from the zod contracts. With --check, fails if the committed
// file is out of date, so every contract change shows up as a reviewable diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { authEndpoints, endpoints } from '../src/index.ts';

const out = fileURLToPath(new URL('../schema/api-v1.json', import.meta.url));
const doc = {
  $comment: 'Generated by packages/contracts/scripts/generate-json-schema.ts. Do not edit by hand.',
  endpoints: Object.fromEntries(
    Object.entries(endpoints).map(([name, e]) => [
      name,
      {
        method: e.method,
        path: e.path,
        ...('request' in e ? { request: z.toJSONSchema(e.request, { io: 'input' }) } : {}),
        response: z.toJSONSchema(e.response),
      },
    ]),
  ),
  authEndpoints: Object.fromEntries(
    Object.entries(authEndpoints).map(([name, e]) => [
      name,
      { method: e.method, path: e.path, ...('request' in e ? { request: z.toJSONSchema(e.request, { io: 'input' }) } : {}) },
    ]),
  ),
};
const text = JSON.stringify(doc, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing counts as changed */ }
  if (current !== text) {
    console.error('packages/contracts/schema/api-v1.json is out of date. Run `pnpm contracts:generate` and commit the result.');
    process.exit(1);
  }
  console.log('API contract snapshot is up to date.');
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${out}`);
}
