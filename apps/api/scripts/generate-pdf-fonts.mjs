// Regenerates src/modules/finance/server/pdf/fonts.generated.ts (Finance F5, docs/finance-documents-f5.md §6).
// The PDF renderer embeds its fonts from this module, so rendering never reads the filesystem or the
// network and the deployed function needs no traced asset files. Source: Inter 4 (SIL OFL 1.1) as
// published in the npm package @expo-google-fonts/inter@0.4.2 (static TTFs from Google Fonts).
//
// Usage: node scripts/generate-pdf-fonts.mjs <dir containing Inter_400Regular.ttf and Inter_600SemiBold.ttf>
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the directory that holds the Inter TTF files.');
const files = { regular: 'Inter_400Regular.ttf', semibold: 'Inter_600SemiBold.ttf' };
let out = `// GENERATED by scripts/generate-pdf-fonts.mjs. Do not edit by hand.
// Inter (https://github.com/rsms/inter), Copyright 2020 The Inter Project Authors, SIL Open Font
// License 1.1 (see ./fonts.LICENSE.txt). Embedded as base64 so the renderer never touches the filesystem.
`;
for (const [name, file] of Object.entries(files)) {
  const bytes = readFileSync(join(dir, file));
  const sha = createHash('sha256').update(bytes).digest('hex');
  out += `\n/** ${file}, ${bytes.length} bytes, sha256 ${sha}. */\nexport const INTER_${name.toUpperCase()}_BASE64 =\n  '${bytes.toString('base64')}';\n`;
}
writeFileSync(new URL('../src/modules/finance/server/pdf/fonts.generated.ts', import.meta.url), out);
console.log('wrote fonts.generated.ts');
